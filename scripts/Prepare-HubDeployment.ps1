$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path $PSScriptRoot -Parent
$functionRoot = Join-Path $taskRoot 'src/Soundshark.Hub/supabase/functions/sounds-hub'
$destination = Join-Path $taskRoot 'outputs/hub-deployment'
New-Item -ItemType Directory -Path $destination -Force | Out-Null
$parts = foreach ($name in 'audio.mjs','auth.mjs','admin.mjs','handler.mjs','index.ts') {
    $source = [IO.File]::ReadAllText((Join-Path $functionRoot $name))
    $source = [regex]::Replace($source, '(?m)^import [^\r\n]+;\r?\n', '')
    $source = [regex]::Replace($source, '(?m)^export ', '')
    $source = [regex]::Replace($source, '(?<=\))!(?=[,\r\n])', '')
    "// $name`n$source"
}
[IO.File]::WriteAllText((Join-Path $destination 'sounds-hub.ts'), "// @ts-nocheck`n// Generated by scripts/Prepare-HubDeployment.ps1. Edit source modules instead.`n" + ($parts -join "`n"))
Copy-Item -LiteralPath (Join-Path $taskRoot 'src/Soundshark.Hub/supabase/setup-account-flow.sql') -Destination (Join-Path $destination 'AccountSetup.sql') -Force
Write-Output "Dashboard files prepared in $destination"

Copy-Item -LiteralPath (Join-Path $taskRoot 'src/Soundshark.Hub/supabase/setup-owner-reports.sql') -Destination (Join-Path $destination 'OwnerReportsSetup.sql') -Force

Copy-Item -LiteralPath (Join-Path $taskRoot 'src/Soundshark.Hub/supabase/setup-submission-limits.sql') -Destination (Join-Path $destination 'SubmissionLimits.sql') -Force
Copy-Item -LiteralPath (Join-Path $taskRoot 'src/Soundshark.Hub/supabase/setup-country-flags.sql') -Destination (Join-Path $destination 'CountryFlagsSetup.sql') -Force
